class LineTraceScreen extends StatefulWidget {
  const LineTraceScreen({super.key, required this.ctx});

  final GameLevelContext ctx;

  @override
  State<LineTraceScreen> createState() => _LineTraceScreenState();
}

class _LineTraceScreenState extends State<LineTraceScreen> {
  late _LevelData _data;
  late List<Point<int>> _path;
  Set<Point<int>> _flashCells = {};
  Color? _flashColor;
  int _failedAttempts = 0;
  bool _locked = false;

  @override
  void initState() {
    super.initState();
    final index = (widget.ctx.level - 1).clamp(0, _levels.length - 1);
    _data = _levels[index];
    _path = [_data.start];
  }

  bool get _isComplete => _path.length > 1 && _path.last == _data.end;

  int _starsForAttempts() {
    if (_failedAttempts <= 0) return 3;
    if (_failedAttempts <= 2) return 2;
    return 1;
  }

  void _handleTouch(Offset local, double cellSize) {
    if (_locked) return;
    final gx = (local.dx / cellSize).round().clamp(0, _data.dotsX - 1);
    final gy = (local.dy / cellSize).round().clamp(0, _data.dotsY - 1);
    final dot = Point(gx, gy);
    if (dot == _path.last) return;

    // Drag-back undo: returning to the second-to-last dot pops the last
    // segment, giving a forgiving undo-by-dragback feel.
    if (_path.length >= 2 && dot == _path[_path.length - 2]) {
      setState(() => _path.removeLast());
      return;
    }

    final last = _path.last;
    final isAdjacent = (dot.x - last.x).abs() + (dot.y - last.y).abs() == 1;
    if (!isAdjacent || _path.contains(dot)) return;

    setState(() => _path.add(dot));
    if (_isComplete) _checkSolution();
  }

  /// Finalizes a drag that ended (lift or system cancel) without reaching
  /// [_LevelData.end]: since tracing is meant to be one continuous stroke
  /// from start to end, an incomplete release abandons the partial trace
  /// (counted as a failed attempt), matching [_clear]'s bookkeeping. A
  /// completed path is already handled by [_checkSolution] before the pan
  /// ever ends, so this is a no-op in that case.
  void _handlePanEnd() {
    if (_locked) return;
    if (_path.length <= 1) return;
    if (_isComplete) return;
    setState(() {
      _failedAttempts++;
      _path = [_data.start];
      _flashCells = {};
      _flashColor = null;
    });
  }

  /// Reveals the next dot beyond wherever the player's current path
  /// currently ends, taken from the verified reference [_LevelData.solution].
  void _showHint() {
    if (_locked || _isComplete) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('This level looks complete!')),
      );
      return;
    }
    final lastDot = _path.last;
    final idx = _data.solution.indexOf(lastDot);
    if (idx == -1 || idx >= _data.solution.length - 1) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text(
            'Your path has drifted from the reference route — try Clear '
            'and retrace from the start dot for a hint.',
          ),
        ),
      );
      return;
    }
    final next = _data.solution[idx + 1];
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(content: Text('Trace toward dot (${next.x}, ${next.y}) next.')),
    );
  }

  void _clear() {
    if (_locked) return;
    setState(() {
      if (_path.length > 1) _failedAttempts++;
      _path = [_data.start];
      _flashCells = {};
      _flashColor = null;
    });
  }

  /// Restarts the current level's attempt from the start dot without
  /// leaving the screen or opening a dialog — the same bookkeeping as the
  /// existing "Clear" button ([_clear]), just reachable from the AppBar
  /// action added for every game, with tap feedback.
  void _restartLevel() {
    Sfx.tap();
    _clear();
  }

  /// Flood-fills the panel's cells, treating drawn path segments as walls
  /// between adjacent cells, and returns the resulting connected regions.
  List<Set<Point<int>>> _computeRegions() {
    final gw = _data.dotsX - 1;
    final gh = _data.dotsY - 1;
    final vWalls = <Point<int>>{}; // (x, y) => vertical segment (x,y)-(x,y+1)
    final hWalls = <Point<int>>{}; // (x, y) => horizontal segment (x,y)-(x+1,y)
    for (var i = 0; i < _path.length - 1; i++) {
      final a = _path[i];
      final b = _path[i + 1];
      if (a.x == b.x) {
        vWalls.add(Point(a.x, min(a.y, b.y)));
      } else {
        hWalls.add(Point(min(a.x, b.x), a.y));
      }
    }

    bool blockedRight(int cx, int cy) => vWalls.contains(Point(cx + 1, cy));
    bool blockedDown(int cx, int cy) => hWalls.contains(Point(cx, cy + 1));

    final visited = <Point<int>>{};
    final regions = <Set<Point<int>>>[];
    for (var cy = 0; cy < gh; cy++) {
      for (var cx = 0; cx < gw; cx++) {
        final start = Point(cx, cy);
        if (visited.contains(start)) continue;
        final region = <Point<int>>{};
        final queue = <Point<int>>[start];
        visited.add(start);
        while (queue.isNotEmpty) {
          final cell = queue.removeLast();
          region.add(cell);
          final x = cell.x;
          final y = cell.y;
          final neighbors = <Point<int>>[
            if (x + 1 < gw && !blockedRight(x, y)) Point(x + 1, y),
            if (x - 1 >= 0 && !blockedRight(x - 1, y)) Point(x - 1, y),
            if (y + 1 < gh && !blockedDown(x, y)) Point(x, y + 1),
            if (y - 1 >= 0 && !blockedDown(x, y - 1)) Point(x, y - 1),
          ];
          for (final n in neighbors) {
            if (visited.add(n)) queue.add(n);
          }
        }
        regions.add(region);
      }
    }
    return regions;
  }

  void _checkSolution() {
    final regions = _computeRegions();
    Set<Point<int>>? offending;
    for (final region in regions) {
      final colorsInRegion = <int>{};
      for (final cell in region) {
        final c = _data.cellColors[cell];
        if (c != null) colorsInRegion.add(c);
      }
      if (colorsInRegion.length > 1) {
        offending = region;
        break;
      }
    }

    if (offending == null) {
      setState(() {
        _locked = true;
        _flashCells = _data.cellColors.keys.toSet();
        _flashColor = AppTheme.success;
      });
      Future.delayed(const Duration(milliseconds: 600), () {
        if (!mounted) return;
        widget.ctx.onComplete(stars: _starsForAttempts());
      });
    } else {
      setState(() {
        _locked = true;
        _flashCells = offending!;
        _flashColor = AppTheme.danger;
        _failedAttempts++;
      });
      Future.delayed(const Duration(milliseconds: 600), () {
        if (!mounted) return;
        setState(() {
          _path = [_data.start];
          _flashCells = {};
          _flashColor = null;
          _locked = false;
        });
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Text('Level ${widget.ctx.level}'),
        actions: [
          ...gameActions(
            context: context,
            def: lineTraceDefinition,
            ctx: widget.ctx,
            onHint: _showHint,
            onRestart: _restartLevel,
          ),
          IconButton(
            icon: const Icon(Icons.flag_outlined),
            tooltip: 'Give up',
            onPressed: widget.ctx.onExit,
          ),
        ],
      ),
      body: Column(
        children: [
          Padding(
            padding: const EdgeInsets.fromLTRB(20, 16, 20, 8),
            child: Text(
              'Attempts: $_failedAttempts',
              style: Theme.of(context).textTheme.titleLarge,
            ),
          ),
          Expanded(
            child: Center(
              child: AspectRatio(
                aspectRatio: 1,
                child: LayoutBuilder(
                  builder: (context, constraints) {
                    const boardPadding = 24.0;
                    final outerSize = constraints.maxWidth;
                    final size = outerSize - boardPadding * 2;
                    final cellSize = size / (_data.dotsX - 1);
                    // GestureDetector wraps the Padding (rather than the
                    // reverse) and is `opaque`, so its hit-test area is the
                    // full outer square, including the padding ring — a
                    // drag starting there no longer misses the board
                    // entirely. `localPosition` is relative to that outer
                    // edge, so it's shifted back by `boardPadding` before
                    // being converted to dot coordinates.
                    Offset toCanvas(Offset local) =>
                        local - const Offset(boardPadding, boardPadding);
                    return GestureDetector(
                      behavior: HitTestBehavior.opaque,
                      onPanStart: (d) =>
                          _handleTouch(toCanvas(d.localPosition), cellSize),
                      onPanUpdate: (d) =>
                          _handleTouch(toCanvas(d.localPosition), cellSize),
                      onPanEnd: (_) => _handlePanEnd(),
                      onPanCancel: _handlePanEnd,
                      child: Padding(
                        padding: const EdgeInsets.all(boardPadding),
                        child: CustomPaint(
                          size: Size(size, size),
                          painter: _LineTracePainter(
                            data: _data,
                            path: _path,
                            flashCells: _flashCells,
                            flashColor: _flashColor,
                          ),
                        ),
                      ),
                    );
                  },
                ),
              ),
            ),
          ),
          Padding(
            padding: const EdgeInsets.fromLTRB(20, 8, 20, 4),
            child: ElevatedButton(
              onPressed: _clear,
              child: const Text('Clear'),
            ),
          ),
          Padding(
            padding: const EdgeInsets.all(20),
            child: Text(
              'Drag from start to end. Every region your path carves out must '
              'contain only one color of square.',
              textAlign: TextAlign.center,
              style: TextStyle(color: AppTheme.textSecondary),
            ),
          ),
        ],
      ),
    );
  }
}

