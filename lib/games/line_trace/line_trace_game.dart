/// One hand-authored puzzle: a dot grid, fixed start/end dots, a map of
/// cell -> constraint color index, and a verified solution path (the exact
/// sequence of dots that solves the panel). The solution is never shown to
/// the player; it exists purely so every level is guaranteed solvable and
/// so the star rating has a reference to compare against.
class _LevelData {
  const _LevelData({
    required this.dotsX,
    required this.dotsY,
    required this.start,
    required this.end,
    required this.cellColors,
    required this.solution,
  });

  final int dotsX;
  final int dotsY;
  final Point<int> start;
  final Point<int> end;

  /// Cell coordinate (cx, cy) -> color index into [_squareColors].
  final Map<Point<int>, int> cellColors;

  /// A verified sequence of dots from [start] to [end] that solves the
  /// panel. Hand-traced and checked against the region algorithm below
  /// while authoring these levels.
  final List<Point<int>> solution;
}

/// A single diagonal staircase path from dot (0,0) to dot (n,n): it always
/// separates an n x n-cell panel into exactly two regions, cells with
/// (cy >= cx) on one side and cells with (cy < cx) on the other, no matter
/// how big `n` is — every (k,k) -> (k+1,k) -> (k+1,k+1) step draws exactly
/// the wall segment needed to keep that split, which is what
/// `_staircase3`/`_staircase4` below were hand-verifying for two fixed
/// sizes. Used to build faster-ramping, larger boards without needing a
/// fresh hand-trace per size.
List<Point<int>> _diagonalStaircase(int n) {
  final points = <Point<int>>[const Point(0, 0)];
  for (var k = 0; k < n; k++) {
    points.add(Point(k + 1, k));
    points.add(Point(k + 1, k + 1));
  }
  return points;
}

